async def ask_llm(messages: list, max_retries: int = 3, base = 1):
    url = "https://openrouter.ai/api/v1/chat/completions"
    headers = {"Authorization": f"Bearer {LLM_TOKEN}",
               "content-type": "application/json"}
    payload = {
        "model" : "recursive/flint-v1.0:free",
        "messages": messages
    }
    async with httpx.AsyncClient() as client:
        
        for attempt in range(max_retries):
            try:
                response = await client.post(url= url, headers=headers, json= payload, timeout=30)
                data = response.json()
                if response.status_code >= 500 or response.status_code == 429:
                        wait = base * (2 ** attempt)
                        await asyncio.sleep(wait)
                        continue
                if 'error' in data:
                    wait = base * (2 ** attempt)
                    await asyncio.sleep(wait)
                    continue
            except httpx.RequestError:
                if attempt == max_retries - 1:
                     raise LLMUnavailableError("LLM не доступен, попробуй позже")
                wait = base * (2 ** attempt)
                await asyncio.sleep(wait)
                continue
            
            return data["choices"][0]["message"]["content"]
        raise LLMUnavailableError("LLM не ответила после всех попыток")



def build_messages(message:str,free_chat: bool,history: list[dict] | None = None):
    if history is None:
         history = []
    if free_chat:
          sys_p = f"{SAM_PERSONA}\n\n{SKILL_STEPS}\n\n{SKILL_ROUTER}"
    else:
         sys_p = f"{SAM_PERSONA}\n\n{SKILL_STEPS}"
    return [
          {"role": 'system', "content": sys_p},
          *history,
         {"role": 'user', "content": message}   
     ]
             
